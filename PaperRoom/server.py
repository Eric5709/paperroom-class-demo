class PostgresConnection:
    # The same application can use durable external PostgreSQL when DATABASE_URL is set.
    def __init__(self):
        import psycopg
        from psycopg.rows import dict_row
        self.connection=psycopg.connect(DATABASE_URL,row_factory=dict_row,connect_timeout=10)
    def execute(self,statement,args=()):
        return self.connection.execute(statement.replace('?', '%s'),args)
    def executescript(self,script):
        for statement in script.split(';'):
            if statement.strip():self.execute(statement)
    def commit(self):return self.connection.commit()
    def rollback(self):return self.connection.rollback()
    def close(self):return self.connection.close()

PG_SCHEMA=SCHEMA.replace('INTEGER PRIMARY KEY AUTOINCREMENT','BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY').replace('content BLOB NOT NULL','content BYTEA NOT NULL')

def sql():
    if DATABASE_URL:
        return PostgresConnection()

    c=sqlite3.connect(DB,timeout=15)
    c.row_factory=sqlite3.Row
    c.execute('PRAGMA foreign_keys=ON')
    c.execute('PRAGMA busy_timeout=15000')
    return c
@contextmanager
def db():
    c=sql()
    try:
        yield c
        c.commit()
    except: c.rollback(); raise
    finally: c.close()
def row(r): return dict(r) if r else None
