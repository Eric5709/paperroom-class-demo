    def do_PATCH(self):self.handle_req('PATCH')
    def do_DELETE(self):self.handle_req('DELETE')
    def handle_req(self,method):
        try:self.route(method)
        except ValueError as e:self.err(400,str(e))
        except BrokenPipeError:pass
        except Exception as e:
            import traceback; traceback.print_exc();self.err(500,'서버 오류가 발생했습니다.')

