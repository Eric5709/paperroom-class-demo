def check_access(c,pid,provided,write=False,owner=False):
    project=c.execute('SELECT * FROM projects WHERE id=?',(pid,)).fetchone()
    if not project:return None,None
    if project['is_demo']:
        if DEMO_READONLY:
            return project, (None if write or owner else 'viewer')
        return project, 'owner'   # Local editable demo only; do not use for confidential research.
    if not provided:return project,None
    v=c.execute('SELECT * FROM tokens WHERE hash=? AND project_id=? AND revoked=0',(sha(provided),pid)).fetchone()
    if not v or (v['expires'] and v['expires']<now()):return project,None
    role=v['role']
    if owner and role!='owner':return project,None
    if write and role not in ('owner','editor'):return project,None
    return project,role

