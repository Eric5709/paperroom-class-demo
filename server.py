    def send(self,code,data=None,typ='application/json; charset=utf-8',extra=None):
        if isinstance(data,(dict,list)): data=json.dumps(data,ensure_ascii=False).encode('utf-8')
        if isinstance(data,str): data=data.encode('utf-8')
        data=data or b''
        self.send_response(code)
        self.send_header('Content-Type',typ)
        self.send_header('Content-Length',str(len(data)))
        self.send_header('Cache-Control','no-store')
        self.send_header('X-Content-Type-Options','nosniff')
        self.send_header('Referrer-Policy','no-referrer')
        self.send_header('X-Frame-Options','DENY')
        self.send_header('Content-Security-Policy',"default-src 'self'; img-src 'self' blob: data:; style-src 'self' 'unsafe-inline'; script-src 'self'; connect-src 'self'; object-src 'none'; base-uri 'self'; frame-ancestors 'none'")
        for k,v in (extra or {}).items():self.send_header(k,v)
        self.end_headers()
        try:self.wfile.write(data)
        except (ConnectionResetError,BrokenPipeError):pass
