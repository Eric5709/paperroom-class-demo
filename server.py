    def data(self):
        try:
            n=int(self.headers.get('Content-Length','0'))
            if n<0 or n>MAX_BODY:raise ValueError('요청 크기가 너무 큽니다 (최대 12MB).')
            v=json.loads(self.rfile.read(n).decode('utf-8'))
            if not isinstance(v,dict):raise ValueError('JSON object만 허용합니다.')
            return v
        except Exception as e:raise ValueError('올바른 요청이 아닙니다: '+str(e))
